#!/usr/bin/env node
// CS Navigator 0.18 RC2 gate: no silent change to deployed 0.17, no false invocation.
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const json=p=>JSON.parse(read(p));
const c=json('registry/curated-methods-v1.json');
const registry=json('registry/public-capabilities-v1.json');
const stable=json('plugins/cs-navigator/plugin.json');
const pack=json('plugins/cs-navigator/capability-pack.json');
const base=read('release/candidates/cs-navigator-v0.18.0-rc1/SKILL.md');
const next=read('release/candidates/cs-navigator-v0.18.0-rc2/SKILL.md');
const m=json('release/candidates/cs-navigator-v0.18.0-rc2/manifest.json');
const experimental=read('mcp/cs-registry-server/src/server.ts');
const quick=read('release/candidates/cs-navigator-v0.18.0-rc2/CONVERSA-RAPIDA.txt');
const guide=read('release/candidates/cs-navigator-v0.18.0-rc2/COMECAR-AQUI.md');
assert.equal(stable.version,'0.17.0');
assert.equal(pack.pack_version,'0.17.0');
assert.equal(read('plugins/cs-navigator/skills/cs-navigator/SKILL.md'),read('skills/featured/cs-navigator/SKILL.md'));
assert.equal(m.version,'0.18.0');
assert.equal(m.state,'implementation-and-access-package-candidate');
assert.equal(m.stable_plugin_not_modified,true);
assert.equal(m.qualification.native_chatgpt,'not-run');
assert.equal(m.qualification.public_distribution,'not-submitted');
assert.equal(m.tool_default_enabled,false);
assert.equal(c.schema_version,1);
assert.equal(c.entries.length,6);
assert.match(c.source_revision,/^[0-9a-f]{40}$/);
const ids=new Set(registry.entries.filter(x=>x.distribution_state==='available').map(x=>x.id));
const seen=new Set();
for(const e of c.entries){
 assert.ok(ids.has(e.id),e.id+' not allowed in public registry');
 assert.ok(!seen.has(e.id));seen.add(e.id);
 assert.ok(!['medical-appointment-prep','caregiver-coordinator'].includes(e.id));
 assert.equal(e.approval_state,'editorial-reviewed');
 assert.equal(e.execution_mode,'guidance-only');
 assert.match(e.source_commit,/^[0-9a-f]{40}$/);
 assert.equal(e.source_commit,c.source_revision);
 assert.match(e.source_path,/^skills\/[a-z0-9\/-]+\/SKILL\.md$/);
 assert.ok(e.steps.length>=1&&e.steps.length<=5);
 assert.ok(e.signals.length>=1&&e.signals.length<=20);
}
const mark='## Universal Curator — 0.18 RC2 candidate\n';
const end='## Personal capability layer';
assert.equal(next.split(mark).length,2);
assert.equal(next.replace(mark+next.split(mark)[1].split(end)[0],''),base);
assert.match(next,/curate_user_goal/);
assert.match(next,/de-identified goal summary/);
assert.match(next,/not a guaranteed plugin invocation/i);
assert.match(next,/Neither is skill installation or execution/i);
assert.match(quick,/NESTA conversa/);
assert.match(quick,/Não invente acesso/);
assert.match(guide,/Skill autônoma/);
assert.match(guide,/Plugin completo/);
assert.match(experimental,/const CURATED_URL="https:\/\/raw\.githubusercontent\.com\/eusourmr\/chatgpt-skills\/main\/registry\/curated-methods-v1\.json"/);
assert.match(experimental,/if \(isExperimentalDeliveryToolEnabled\(process\.env\.CS_ENABLE_EXPERIMENTAL_DELIVERY_TOOL\)\)/);
const names=[...experimental.matchAll(/server\.registerTool\(\s*"([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(names.sort(),['search_capabilities','get_capability','get_evidence','registry_status','assess_capability_delivery','curate_user_goal'].sort());
assert.doesNotMatch(experimental,/server\.registerPrompt\(/);
console.log('PASS — 0.18 RC2 curated methods, three access paths, 0.17 isolation, experimental tool default-off');
